import React, { useEffect, useState } from 'react';
import { X, LoaderCircle } from 'lucide-react';

const API_DEPARTMENTS_URL = 'http://127.0.0.1:8000/api/departments/';

function getLocalDateString() {
  const now = new Date();
  const year = now.getFullYear();
  const month = String(now.getMonth() + 1).padStart(2, '0');
  const day = String(now.getDate()).padStart(2, '0');
  return `${year}-${month}-${day}`;
}

const INITIAL_FORM = {
  subject: '',
  dept: '',
  semester: '1',
  date: getLocalDateString(),
  time: '10:00 AM - 1:00 PM',
  room: 'Hall A-102',
};

function getErrorMessage(error) {
  if (!error) return 'Unable to schedule the examination.';
  if (typeof error === 'string') return error;
  if (error.detail) return error.detail;
  return Object.entries(error)
    .map(([field, messages]) => `${field}: ${Array.isArray(messages) ? messages.join(', ') : messages}`)
    .join(' ');
}

export default function ScheduleExamModal({ isOpen, onClose, onScheduleExam }) {
  const [formData, setFormData] = useState(INITIAL_FORM);
  const [departments, setDepartments] = useState([]);
  const [departmentsLoading, setDepartmentsLoading] = useState(false);
  const [departmentError, setDepartmentError] = useState('');
  const [saving, setSaving] = useState(false);
  const [submitError, setSubmitError] = useState('');
  const today = getLocalDateString();

  useEffect(() => {
    if (!isOpen) return;
    const currentLocalDate = getLocalDateString();
    setFormData((current) => ({
      ...current,
      date: current.date < currentLocalDate ? currentLocalDate : current.date,
    }));
  }, [isOpen]);

  useEffect(() => {
    if (!isOpen) return undefined;

    const controller = new AbortController();
    const loadDepartments = async () => {
      setDepartmentsLoading(true);
      setDepartmentError('');
      try {
        const response = await fetch(API_DEPARTMENTS_URL, { signal: controller.signal });
        const result = await response.json();
        if (!response.ok) throw new Error(getErrorMessage(result));

        const list = Array.isArray(result) ? result : [];
        setDepartments(list);
        setFormData((current) => ({
          ...current,
          dept: current.dept && list.includes(current.dept) ? current.dept : (list[0] || ''),
        }));
      } catch (error) {
        if (error.name !== 'AbortError') {
          setDepartmentError(error.message || 'Unable to load departments.');
        }
      } finally {
        if (!controller.signal.aborted) setDepartmentsLoading(false);
      }
    };

    loadDepartments();
    return () => controller.abort();
  }, [isOpen]);

  if (!isOpen) return null;

  const updateField = (field, value) => {
    setFormData((current) => ({ ...current, [field]: value }));
    setSubmitError('');
  };

  const handleSubmit = async (event) => {
    event.preventDefault();
    if (!formData.subject.trim() || !formData.dept || !formData.date) return;
    if (formData.date < today) {
      setSubmitError('Past exam dates are not allowed. Please select today or a future date.');
      return;
    }

    setSaving(true);
    setSubmitError('');
    try {
      await onScheduleExam({
        subject: formData.subject.trim(),
        dept: formData.dept,
        semester: Number(formData.semester),
        date: formData.date,
        time: formData.time,
        room: formData.room.trim(),
      });
      setFormData({ ...INITIAL_FORM, dept: departments[0] || '' });
      onClose();
    } catch (error) {
      setSubmitError(getErrorMessage(error.message || error));
    } finally {
      setSaving(false);
    }
  };

  const inputClass = 'w-full px-3.5 py-2.5 bg-[#F4F7FE] border border-slate-200 rounded-xl text-sm focus:outline-none focus:ring-2 focus:ring-blue-500/30 focus:bg-white disabled:opacity-60';
  const labelClass = 'block text-xs font-semibold text-slate-700 mb-1';

  return (
    <div className="fixed inset-0 z-50 flex items-center justify-center bg-slate-900/50 backdrop-blur-xs p-4">
      <div className="bg-white rounded-2xl w-full max-w-md max-h-[90vh] overflow-y-auto p-6 shadow-xl border border-slate-100">
        <div className="flex items-center justify-between pb-3 border-b border-slate-100">
          <h3 className="text-lg font-bold text-slate-800">Schedule New Exam</h3>
          <button type="button" onClick={onClose} disabled={saving} aria-label="Close modal" className="p-1.5 text-slate-400 hover:bg-slate-100 rounded-lg cursor-pointer disabled:opacity-50">
            <X className="w-5 h-5" />
          </button>
        </div>

        <form onSubmit={handleSubmit} className="mt-4 space-y-4">
          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className={labelClass}>Subject Code</label>
              <div className={`${inputClass} flex items-center justify-between text-slate-500 cursor-not-allowed`} aria-readonly="true">
                <span>Auto-generated by system</span>
                <span className="text-[10px] font-bold uppercase tracking-wide text-emerald-600">Automatic</span>
              </div>
              <p className="mt-1 text-[10px] text-slate-400">Generated after you publish the exam.</p>
            </div>
            <div>
              <label className={labelClass}>Department *</label>
              <select required value={formData.dept} onChange={(e) => updateField('dept', e.target.value)} disabled={departmentsLoading || departments.length === 0} className={inputClass}>
                <option value="">{departmentsLoading ? 'Loading departments...' : 'Select department'}</option>
                {departments.map((department) => <option key={department} value={department}>{department}</option>)}
              </select>
              {departmentError && <p className="text-xs text-red-600 mt-1">{departmentError}</p>}
              {!departmentsLoading && !departmentError && departments.length === 0 && <p className="text-xs text-amber-600 mt-1">No departments found. Add a department to an existing student or faculty record first.</p>}
            </div>
          </div>

          <div>
            <label className={labelClass}>Subject Name *</label>
            <input type="text" required maxLength={100} placeholder="e.g. Operating Systems" value={formData.subject} onChange={(e) => updateField('subject', e.target.value)} className={inputClass} />
          </div>

          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className={labelClass}>Semester *</label>
              <select required value={formData.semester} onChange={(e) => updateField('semester', e.target.value)} className={inputClass}>
                {Array.from({ length: 8 }, (_, index) => <option key={index + 1} value={String(index + 1)}>{index + 1}{index === 0 ? 'st' : index === 1 ? 'nd' : index === 2 ? 'rd' : 'th'} Semester</option>)}
              </select>
            </div>
            <div>
              <label className={labelClass}>Exam Date *</label>
              <input type="date" required min={today} value={formData.date} onChange={(e) => updateField('date', e.target.value)} className={inputClass} />
            </div>
          </div>

          <div className="grid grid-cols-2 gap-3">
            <div>
              <label className={labelClass}>Room / Hall *</label>
              <input type="text" required maxLength={50} placeholder="e.g. Hall A-102" value={formData.room} onChange={(e) => updateField('room', e.target.value)} className={inputClass} />
            </div>
            <div>
              <label className={labelClass}>Time Slot *</label>
              <select value={formData.time} onChange={(e) => updateField('time', e.target.value)} className={inputClass}>
                <option value="10:00 AM - 1:00 PM">10:00 AM - 1:00 PM (Morning)</option>
                <option value="2:00 PM - 5:00 PM">2:00 PM - 5:00 PM (Afternoon)</option>
              </select>
            </div>
          </div>

          {submitError && <div role="alert" className="rounded-xl border border-red-200 bg-red-50 px-3 py-2 text-xs text-red-700">{submitError}</div>}

          <div className="flex justify-end gap-3 pt-4 border-t border-slate-100">
            <button type="button" onClick={onClose} disabled={saving} className="px-4 py-2 text-xs font-semibold text-slate-600 bg-slate-100 hover:bg-slate-200 rounded-xl cursor-pointer disabled:opacity-50">Cancel</button>
            <button type="submit" disabled={saving || departmentsLoading || departments.length === 0} className="px-5 py-2 text-xs font-semibold text-white bg-[#1464F6] hover:bg-blue-700 rounded-xl shadow-sm cursor-pointer disabled:opacity-60 disabled:cursor-not-allowed inline-flex items-center gap-2">
              {saving && <LoaderCircle className="w-4 h-4 animate-spin" />}
              {saving ? 'Saving...' : 'Publish Schedule'}
            </button>
          </div>
        </form>
      </div>
    </div>
  );
}
